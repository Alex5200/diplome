  c.push(h.p("Реализованная среда симуляции является основой для дальнейших исследований в области обучения с подкреплением. Планируется применение алгоритмов PPO (Proximal Policy Optimization) и SAC (Soft Actor-Critic) для обучения политик захвата объектов с последующим переносом на реального робота (sim-to-real transfer)."));

