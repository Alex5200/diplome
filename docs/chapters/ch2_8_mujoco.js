  c.push(h.codeCaption("Листинг 2.16 — Метод step() класса RobotEnv"));
  c.push(...h.codeBlock([
    "def step(self, action: np.ndarray) -> Tuple[Dict, float, bool, Dict]:",
    "    # Применить действие к суставам",
    "    for i in range(6):",
    "        self.data.ctrl[i] = action[i] * self.joint_ranges[i]",
    "    self.data.ctrl[6] = action[6] * 0.04  # гриппер",
    "    mujoco.mj_step(self.model, self.data)",
    "",
    "    # Собрать наблюдение",
    "    obs = {",
    "        'joint_angles': self.data.qpos[:6].copy(),",
    "        'ee_pos': self.data.sensor('ee_pos').data.copy(),",
    "        'rgb': self._render_camera('top', 640, 480),",
    "        'depth': self._render_depth('top', 640, 480),",
    "    }",
    "    # Вычислить награду",
    "    dist = np.linalg.norm(obs['ee_pos'] - self.target_pos)",
    "    reward = -dist + self._grasp_bonus()",
    "    done = dist < 0.01  # 1 см до цели",
    "    return obs, reward, done, {}",
  ]));
  c.push(h.emptyLine());

  c.push(h.p("Функция награды (reward) в листинге 2.16 реализует стратегию «отрицательное расстояние + бонус за захват»: агент получает штраф, пропорциональный расстоянию от конечного эффектора до целевого объекта, и бонус при успешном контакте гриппера с объектом. Эпизод завершается (done = True), когда расстояние до цели становится менее 1 см."));

