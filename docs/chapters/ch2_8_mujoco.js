  c.push(h.heading3("Программная генерация MJCF-модели"));

  c.push(h.p("В отличие от традиционного подхода, при котором модель робота описывается в статическом XML-файле формата MJCF, в данной работе модель генерируется программно на основе DH-параметров реального робота. Это обеспечивает автоматическую синхронизацию между кинематической моделью (app/models/kinematics.py) и физической симуляцией: при изменении длин звеньев или конфигурации суставов достаточно перезапустить генератор модели."));

  c.push(h.p("Генератор формирует полное описание робота в формате MJCF (MuJoCo XML), включающее:"));

