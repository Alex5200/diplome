module.exports = function (h) {
  const c = [];

  c.push(h.heading2("2.3 Реализация кинематического модуля"));

  c.push(h.p("Кинематический модуль является вычислительным ядром системы, обеспечивающим преобразование между пространством углов суставов (joint space) и декартовым пространством (Cartesian space). Модуль реализован в файле app/models/kinematics.py (640 строк) и содержит два основных класса: RobotKinematics6DOF для прямой кинематики и InverseKinematics6DOF для обратной кинематики. Дополнительно реализован сервис KinematicsService (app/services/kinematics_service.py, 224 строки), обеспечивающий кэширование результатов и проверку досягаемости."));

  // --- FK ---
  c.push(h.heading3("Реализация прямой кинематики"));

  c.push(h.p("Класс RobotKinematics6DOF реализует вычисление прямой кинематики по методу Денавита–Хартенберга, теоретические основы которого описаны в разделе 1.4. При инициализации класса задаются длины звеньев робота и DH-параметры для каждого из шести суставов. Метод forward_kinematics принимает массив из шести углов в градусах и возвращает позиции всех промежуточных суставов и конечного эффектора."));

  c.push(h.codeCaption("Листинг 2.5 — Инициализация DH-параметров робота"));
  c.push(...h.codeBlock([
    "class RobotKinematics6DOF:",
    "    L0, L1, L2, L3, L4, L5 = 19.0, 134.0, 95.0, 34.0, 35.0, 0.0",
    "",
    "    def __init__(self):",
    "        # DH-параметры: [d, a, alpha]",
    "        self.dh_params = [",
    "            (self.L0, 0.0, math.pi/2),   # J1: база — поворот + подъём",
    "            (0.0, self.L1, 0.0),          # J2: плечо 1 — 134 мм",
    "            (0.0, self.L2, 0.0),          # J3: плечо 2 — 95 мм",
    "            (0.0, self.L3, math.pi/2),    # J4: локоть — 34 мм",
    "            (0.0, self.L4, -math.pi/2),   # J5: кисть 1 — 35 мм",
    "            (self.L5, 0.0, 0.0),          # J6: кисть 2 — 0 мм",
    "        ]",
    "        self.max_reach = sum([self.L1, self.L2, self.L3, self.L4])  # 298 мм",
  ]));
  c.push(h.emptyLine());

  c.push(h.p("Максимальная досягаемость робота составляет 298 мм в горизонтальной плоскости (сумма L1 + L2 + L3 + L4), а с учётом вертикального смещения базы (L0 = 19 мм) общая досягаемость достигает 317 мм от начала координат. Эти значения используются KinematicsService для быстрой предварительной проверки целевых точек перед запуском вычислительно затратного алгоритма IK."));

  c.push(h.p("Ключевым вычислительным элементом является метод _dh_matrix, формирующий матрицу однородного преобразования 4×4 для каждого сустава. Матрица объединяет вращение вокруг оси Z на угол θ, линейное смещение вдоль Z на величину d, линейное смещение вдоль X на величину a и вращение вокруг оси X на угол α:"));

  c.push(h.codeCaption("Листинг 2.6 — Формирование DH-матрицы преобразования"));
  c.push(...h.codeBlock([
    "def _dh_matrix(self, theta, d, a, alpha):",
    "    ct, st = math.cos(theta), math.sin(theta)",
    "    ca, sa = math.cos(alpha), math.sin(alpha)",
    "    return [",
    "        [ct, -st*ca,  st*sa,  a*ct],",
    "        [st,  ct*ca, -ct*sa,  a*st],",
    "        [0,   sa,     ca,     d   ],",
    "        [0,   0,      0,      1   ]",
    "    ]",
  ]));
  c.push(h.emptyLine());

  c.push(h.p("Полная прямая кинематика вычисляется последовательным умножением шести DH-матриц. На каждом шаге сохраняется промежуточная позиция сустава, что позволяет визуализировать полную цепочку звеньев робота в 3D:"));

  c.push(h.formula("T₀⁶ = T₁ · T₂ · T₃ · T₄ · T₅ · T₆", "2.4"));

  c.push(h.p("Позиция конечного эффектора извлекается из последнего столбца результирующей матрицы T₀⁶: x = T[0][3], y = T[1][3], z = T[2][3]. Вычислительная сложность прямой кинематики составляет O(n), где n = 6 — количество суставов. На современном процессоре одно вычисление FK занимает менее 0.01 мс, что позволяет выполнять его в реальном времени без заметных задержек."));

  // --- IK ---
  c.push(h.heading3("Реализация обратной кинематики"));

  c.push(h.p("Класс InverseKinematics6DOF реализует решение обратной кинематической задачи методом демпфированных наименьших квадратов (Damped Least Squares, DLS), теоретические основы которого изложены в разделе 1.4. Алгоритм состоит из трёх последовательных этапов: проверка досягаемости целевой точки, генерация множественных начальных приближений и итеративная численная оптимизация для каждого приближения с выбором лучшего решения."));

  c.push(h.p("На первом этапе вычисляется евклидово расстояние от начала координат до целевой точки и сравнивается с максимальной досягаемостью робота. Если расстояние превышает 317 мм, алгоритм немедленно возвращает None без запуска оптимизации. На втором этапе формируются 11 начальных приближений, покрывающих различные характерные конфигурации манипулятора: вытянутая, согнутая вверх, согнутая вниз, повёрнутая влево/вправо и их комбинации. Для каждого приближения угол базового сустава J1 корректируется аналитически:"));

  c.push(h.formula("θ₁ = atan2(y, x)", "2.5"));

  c.push(h.p("Третий этап — итеративная оптимизация — является вычислительно наиболее затратным. На каждой итерации вычисляется якобиан размерности 3×6 методом центральных конечных разностей:"));

  c.push(h.formula("J[i][j] ≈ (pᵢ(θⱼ + Δ) − pᵢ(θⱼ − Δ)) / (2Δ),  Δ = 0.5°", "2.6"));

  c.push(h.p("Вычисление якобиана требует 12 вызовов прямой кинематики (по 2 на каждый из 6 суставов), что делает его доминирующей операцией по затратам. Обновление углов суставов на каждой итерации выполняется по формуле DLS:"));

  c.push(h.formula("δθ = Jᵀ · (J · Jᵀ + λ² · I)⁻¹ · e,  λ = 1.0", "2.7"));

  c.push(h.p("где e — вектор ошибки позиции (разность между целевой и текущей позицией конечного эффектора), λ — параметр демпфирования. После обновления углы ограничиваются диапазоном [−179°, +179°] для предотвращения выхода за физические пределы суставов. Критерий сходимости — евклидова норма ошибки менее заданного порога (по умолчанию 0.5 мм). Максимальное число итераций — 300."));

  c.push(h.codeCaption("Листинг 2.7 — Основной цикл оптимизации DLS"));
  c.push(...h.codeBlock([
    "def _numerical_solve(self, x, y, z, initial_angles, max_iter=300, tol=0.5):",
    "    angles = list(initial_angles)",
    "    damping = 1.0",
    "    for iteration in range(max_iter):",
    "        pos = self.kinematics.get_end_effector_position(angles)",
    "        error = np.array([x - pos[0], y - pos[1], z - pos[2]])",
    "        if np.linalg.norm(error) < tol:",
    "            return angles  # сходимость достигнута",
    "        J = self._compute_jacobian(angles)",
    "        JJT = J @ J.T",
    "        damped = JJT + (damping**2) * np.eye(3)",
    "        delta_theta = J.T @ np.linalg.solve(damped, error)",
    "        step = min(1.0, 5.0 / (np.max(np.abs(delta_theta)) + 1e-6))",
    "        for i in range(6):",
    "            angles[i] = np.clip(angles[i] + delta_theta[i] * step, -179, 179)",
    "    return angles  # возвращаем лучшее найденное приближение",
  ]));
  c.push(h.emptyLine());

  c.push(h.p("Листинг 2.7 демонстрирует реализацию основного цикла оптимизации. Адаптивный размер шага (переменная step) ограничивает максимальное изменение угла за одну итерацию до 5°, что предотвращает «прыжки» через сингулярные конфигурации и обеспечивает устойчивую сходимость."));

  // --- KinematicsService ---
  c.push(h.heading3("Сервис кинематики"));

  c.push(h.p("KinematicsService (app/services/kinematics_service.py) предоставляет высокоуровневый API для доступа к кинематическим вычислениям. Основные функции сервиса: кэширование результатов FK и IK для повторяющихся запросов, проверка досягаемости целевых точек, преобразование между различными представлениями углов (градусы, радианы, позиции моторов) и валидация ограничений суставов."));

  c.push(h.p("Кэширование реализовано с использованием LRU-стратегии (Least Recently Used) с размером кэша 256 записей для FK и 64 записи для IK. Эффективность кэширования особенно высока при работе с GUI, где пользователь часто возвращается к ранее заданным конфигурациям. Экспериментально установлено, что при типичном сценарии работы (интерактивное перемещение суставов) коэффициент попадания в кэш составляет 30–40%."));

  c.push(h.emptyLine());
  c.push(h.tableCaption("Таблица 2.5 — Производительность кинематических вычислений"));
  c.push(h.makeTable(
    ["Операция", "Время (мс)", "Итераций", "Вызовов FK", "Примечание"],
    [
      ["FK (одно вычисление)", "< 0.01", "—", "1", "Линейная сложность O(n)"],
      ["IK (одно приближение)", "3–15", "50–300", "100–3600", "Зависит от начальной позиции"],
      ["IK (11 приближений)", "30–150", "550–3300", "1100–39600", "Худший случай — 150 мс"],
      ["IK (кэш-попадание)", "< 0.001", "—", "—", "LRU-кэш, O(1)"],
    ],
    [2400, 1400, 1400, 1400, 2400]
  ));
  c.push(h.emptyLine());

  c.push(h.p("Таблица 2.5 показывает производительность кинематических вычислений. Даже в худшем случае (11 приближений, 300 итераций каждое) время решения IK не превышает 150 мс, что является приемлемым для интерактивного управления. В типичном случае решение находится за 30–50 мс, так как большинство приближений сходятся значительно быстрее максимума."));

  c.push(h.pageBreak());
  return c;
};
