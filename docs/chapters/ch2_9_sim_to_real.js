/**
 * ГЛАВА 2.9 — Зеркалирование симуляции на реальный робот (Sim-to-Real)
 *
 * Содержание:
 *   - Концепция и архитектура sim-to-real переноса
 *   - Модуль SimToRealMirror: режимы, транспорты, безопасность
 *   - Режим sim_to_real: MuJoCo → реальный ST3215
 *   - Режим real_to_sim: телеоперация и запись датасетов
 *   - Транспорт: прямой UART и ROS2
 *   - Скрипт run_mirror.py: интерактивный запуск
 *   - Диаграмма взаимодействия компонентов
 *
 * Нумерация: таблицы 2.16–2.17, рисунок 2.13, листинги 2.20–2.22
 * Целевой объём: ~3 страницы
 */
module.exports = function (h) {
  const c = [];

  // ─────────────────────────────────────────────────────────────────────
  // Заголовок раздела
  // ─────────────────────────────────────────────────────────────────────
  c.push(h.heading2("2.9 Зеркалирование симуляции на реальный робот"));

  c.push(h.p(
    "Sim-to-real transfer (перенос из симуляции на реальное устройство) — " +
    "одна из ключевых задач современной робототехники. В рамках данной работы " +
    "реализован модуль SimToRealMirror, обеспечивающий двунаправленную синхронизацию " +
    "состояния между симуляцией MuJoCo и физическим роботом ST3215 в режиме реального " +
    "времени. Модуль размещён в файле mujoco_sim/src/mujoco_robot_sim/sim_to_real.py " +
    "и предоставляет два режима работы, два транспортных протокола и механизм " +
    "защиты от выхода суставов за допустимые пределы."
  ));

  // ─────────────────────────────────────────────────────────────────────
  // 2.9.1 Архитектура
  // ─────────────────────────────────────────────────────────────────────
  c.push(h.heading3("Архитектура модуля"));

  c.push(h.p(
    "SimToRealMirror работает как фоновый поток (daemon thread), " +
    "не блокируя основной цикл симуляции и viewer. " +
    "В режиме sim_to_real на каждом такте поток вызывает " +
    "MuJoCoRobotController.get_joint_angles(), применяет проверку " +
    "безопасности и отправляет команды позиционирования на реальный робот " +
    "с заданной частотой (по умолчанию 20 Гц). " +
    "В режиме real_to_sim поток читает углы с физических серводвигателей " +
    "и обновляет состояние симуляции через set_joint_angles(), " +
    "обеспечивая корреляцию виртуального и физического состояния. " +
    "Взаимодействие компонентов показано на рисунке 2.12."
  ));

  c.push(h.emptyLine());
  c.push(...h.figurePlaceholder("Рисунок 2.12 — Схема взаимодействия компонентов SimToRealMirror"));
  c.push(h.emptyLine());

  c.push(h.p(
    "Архитектурно модуль состоит из трёх уровней: уровень управления состоянием " +
    "(класс MirrorStats), уровень транспорта (методы _send_serial и _send_ros2) " +
    "и уровень основного цикла (_mirror_loop). " +
    "Разделение уровней позволяет независимо заменять транспортный механизм, " +
    "не изменяя логику зеркалирования."
  ));

  // ─────────────────────────────────────────────────────────────────────
  // 2.9.2 Режимы работы
  // ─────────────────────────────────────────────────────────────────────
  c.push(h.heading3("Режимы работы"));

  c.push(h.p(
    "Модуль поддерживает два режима, выбираемых параметром mode при инициализации. " +
    "Таблица 2.16 описывает характеристики каждого режима."
  ));

  c.push(h.emptyLine());
  c.push(h.tableCaption("Таблица 2.16 — Режимы работы SimToRealMirror"));
  c.push(h.makeTable(
    ["Параметр", "sim_to_real", "real_to_sim"],
    [
      ["Направление потока данных",
        "MuJoCo → реальный робот",
        "Реальный робот → MuJoCo"],
      ["Метод чтения состояния",
        "ctrl.get_joint_angles()",
        "ctrl.read_real_angles()"],
      ["Метод записи состояния",
        "ST3215.MoveTo() / /robot/joint_cmd",
        "ctrl.set_joint_angles()"],
      ["Применение safety clamping",
        "Да — перед отправкой",
        "Нет (робот сам ограничен)"],
      ["Типичное применение",
        "Управление через симуляцию, демонстрация алгоритмов",
        "Телеоперация, сбор датасетов для RL"],
      ["Требует подключения к железу",
        "Да",
        "Да"],
    ],
    [2600, 3200, 3200]
  ));
  c.push(h.emptyLine());

  c.push(h.p(
    "Режим sim_to_real является основным и используется для демонстрации алгоритмов " +
    "управления: оператор взаимодействует с симуляцией через viewer или команды в " +
    "терминале, а реальный робот воспроизводит заданные позы. " +
    "Режим real_to_sim применяется для записи обучающих датасетов: оператор вручную " +
    "управляет физическим роботом, одновременно получая визуальное подтверждение " +
    "корректности чтения углов в симуляторе. " +
    "Оба режима могут работать с частотой до 50 Гц, однако рекомендуемое значение " +
    "для реального железа составляет 20–30 Гц во избежание перегрева и " +
    "вибраций серводвигателей."
  ));

  // ─────────────────────────────────────────────────────────────────────
  // 2.9.3 Транспортные протоколы
  // ─────────────────────────────────────────────────────────────────────
  c.push(h.heading3("Транспортные протоколы"));

  c.push(h.p(
    "SimToRealMirror поддерживает два транспортных протокола для отправки команд " +
    "на реального робота, выбираемых параметром transport."
  ));

  c.push(h.bulletDash(
    "Serial (UART) — прямое подключение к контроллеру ST3215 через последовательный порт. " +
    "На каждом такте зеркала для каждого из шести суставов вычисляется значение позиции " +
    "в диапазоне 0–4095, применяется инверсия (для суставов с перевёрнутой полярностью) " +
    "и отправляется команда ST3215.MoveTo(motor_id, position, speed, acc). " +
    "Транспорт обеспечивает минимальную задержку (~2 мс) и не требует дополнительной инфраструктуры."
  ));
  c.push(h.bulletDash(
    "ROS2 (опционально) — публикация команды позиционирования в топик " +
    "/robot/joint_cmd типа trajectory_msgs/JointTrajectoryPoint. " +
    "Транспорт активируется при наличии пакета rclpy и запущенном узле robot_node_v2. " +
    "Углы конвертируются из градусов в радианы перед публикацией. " +
    "Данный режим позволяет задействовать всю инфраструктуру ROS2, " +
    "включая логирование, rosbag2 и ros2_control."
  ));

  c.push(h.codeCaption("Листинг 2.17 — Инициализация и запуск SimToRealMirror"));
  c.push(...h.codeBlock([
    "from mujoco_robot_sim import MuJoCoRobotController, generate_robot_mjcf",
    "from mujoco_robot_sim.sim_to_real import SimToRealMirror",
    "",
    "# Создать симуляцию",
    "ctrl = MuJoCoRobotController(generate_robot_mjcf())",
    "",
    "# Запустить зеркало: sim → реальный робот через UART",
    "mirror = SimToRealMirror(",
    "    ctrl,",
    "    mode=\"sim_to_real\",       # или \"real_to_sim\"",
    "    transport=\"serial\",       # или \"ros2\"",
    "    port=\"COM3\",",
    "    rate_hz=20.0,              # частота зеркалирования",
    "    motor_speed=300,           # скорость моторов ST3215 (50–3400)",
    "    safety_check=True,         # ограничить углы безопасными пределами",
    ")",
    "",
    "mirror.start()  # подключает робота и запускает фоновый поток",
    "# ... основной цикл ...",
    "mirror.stop()   # отключает поток и закрывает соединение",
  ]));
  c.push(h.emptyLine());

  // ─────────────────────────────────────────────────────────────────────
  // 2.9.4 Механизм безопасности
  // ─────────────────────────────────────────────────────────────────────
  c.push(h.heading3("Механизм безопасности"));

  c.push(h.p(
    "Перед отправкой команды на реальный робот модуль применяет " +
    "ограничение (clamping) углов до безопасных пределов, " +
    "определённых константой MuJoCoRobotController.SAFE_ANGLE_LIMITS_DEG. " +
    "Это предотвращает повреждение механических ограничителей при выходе " +
    "симуляции за физически допустимые пределы движения. " +
    "Таблица 2.17 приводит безопасные диапазоны для каждого сустава."
  ));

  c.push(h.emptyLine());
  c.push(h.tableCaption("Таблица 2.17 — Безопасные пределы суставов (SAFE_ANGLE_LIMITS_DEG)"));
  c.push(h.makeTable(
    ["Сустав", "Ось вращения", "Минимум (°)", "Максимум (°)", "Диапазон (°)"],
    [
      ["joint_0 — основание",  "Z", "−120", "+120", "240"],
      ["joint_1 — плечо",      "Y", "−45",  "+90",  "135"],
      ["joint_2 — локоть",     "Y", "−90",  "+45",  "135"],
      ["joint_3 — кисть 1",    "Y", "−120", "0",    "120"],
      ["joint_4 — кисть 2",    "X", "−90",  "+90",  "180"],
      ["joint_5 — инструмент", "Z", "−90",  "+90",  "180"],
    ],
    [2400, 1800, 1600, 1600, 1600]
  ));
  c.push(h.emptyLine());

  c.push(h.p(
    "Помимо ограничения углов, модуль ведёт статистику работы через класс " +
    "MirrorStats: счётчик отправленных команд, счётчик ошибок, " +
    "счётчик пропущенных кадров (при превышении времени такта) и скользящее " +
    "среднее реальной частоты за последние 50 кадров. " +
    "Статистика доступна через свойство mirror.stats и периодически выводится " +
    "в лог (по умолчанию каждые 10 секунд)."
  ));

  // ─────────────────────────────────────────────────────────────────────
  // 2.9.5 Скрипт run_mirror.py
  // ─────────────────────────────────────────────────────────────────────
  c.push(h.heading3("Интерактивный запуск: run_mirror.py"));

  c.push(h.p(
    "Для удобства работы реализован скрипт mujoco_sim/scripts/run_mirror.py, " +
    "объединяющий запуск MuJoCo viewer, инициализацию SimToRealMirror и " +
    "обработку команд в терминале в единый процесс. " +
    "Скрипт использует mujoco.viewer.launch_passive() для неблокирующего открытия " +
    "окна симуляции и запускает поток обработки команд пользователя параллельно " +
    "с основным физическим циклом (mujoco.mj_step + viewer.sync)."
  ));

  c.push(h.codeCaption("Листинг 2.18 — Запуск зеркала через скрипт run_mirror.py"));
  c.push(...h.codeBlock([
    "# Режим sim_to_real через UART (по умолчанию)",
    "python scripts/run_mirror.py --port COM3",
    "",
    "# Повышенная скорость и частота",
    "python scripts/run_mirror.py --port COM3 --rate 30 --speed 500",
    "",
    "# Режим real_to_sim (движение реального робота отображается в симуляции)",
    "python scripts/run_mirror.py --port COM3 --mode real_to_sim",
    "",
    "# Через ROS2 (требует запущенного robot_node_v2)",
    "python scripts/run_mirror.py --port COM3 --transport ros2",
    "",
    "# Запуск без реального робота (отладка симуляции)",
    "python scripts/run_mirror.py --dry-run",
    "",
    "# Команды в терминале во время работы:",
    "#   angles 0 -30 45 0 0 0   — задать позу суставам (градусы)",
    "#   goto 100 0 150           — IK к точке (мм)",
    "#   speed 400                — изменить скорость моторов",
    "#   stats                    — показать статистику",
    "#   pause / resume           — приостановить/возобновить",
    "#   q                        — выход",
  ]));
  c.push(h.emptyLine());

  c.push(h.p(
    "Скрипт также доступен через главную точку входа mujoco_sim/main.py " +
    "с флагом --mirror. Оба способа запуска поддерживают одинаковый набор " +
    "параметров командной строки: --port, --baudrate, --mode, --transport, " +
    "--rate, --speed, --no-safety и --dry-run."
  ));

  // ─────────────────────────────────────────────────────────────────────
  // 2.9.6 Интеграция с ROS2
  // ─────────────────────────────────────────────────────────────────────
  c.push(h.heading3("Интеграция с ros2_control"));

  c.push(h.p(
    "При выборе транспорта ros2 SimToRealMirror публикует команды в топик " +
    "/robot/joint_cmd, подписчиком которого является узел robot_node_v2 " +
    "(ros2/robot_control/robot_node_v2.py). " +
    "Узел принимает JointTrajectoryPoint с шестью позициями в радианах, " +
    "конвертирует их в единицы серводвигателя (0–4095) и отправляет по UART. " +
    "При дополнительном использовании ros2_control (глава 2.9) " +
    "команды проходят через JointTrajectoryController и мост " +
    "ros2_control_bridge.py, обеспечивая полную совместимость с " +
    "инфраструктурой стека ros2_controllers."
  ));

  c.push(h.codeCaption("Листинг 2.19 — Полная цепочка sim → ros2_control → реальный робот"));
  c.push(...h.codeBlock([
    "# Терминал 1: запуск ros2_control стека",
    "ros2 launch robot_control ros2_control.launch.py port:=COM3",
    "",
    "# Терминал 2: запуск зеркала с транспортом ros2",
    "python scripts/run_mirror.py --transport ros2 --dry-run",
    "#   (--dry-run: железо управляется через ros2_control_bridge, а не напрямую)",
    "",
    "# Цепочка передачи данных:",
    "#   MuJoCo get_joint_angles()",
    "#      └─► /robot/joint_cmd (rad)  [SimToRealMirror, 20 Гц]",
    "#            └─► robot_node_v2 (подписчик)",
    "#                  └─► MotorController.move_joint()",
    "#                        └─► ST3215.MoveTo()  [UART]",
    "#                              └─► Реальный серводвигатель",
    "",
    "# Альтернативная цепочка через JointTrajectoryController:",
    "#   MuJoCo get_joint_angles()",
    "#      └─► /joint_trajectory_controller/follow_joint_trajectory (action)",
    "#            └─► JTC → mock hardware → ros2_control_bridge",
    "#                  └─► RobotHWInterface.write_joint_positions()",
    "#                        └─► ST3215.MoveTo()  [UART]",
  ]));
  c.push(h.emptyLine());

  c.push(h.p(
    "Таким образом, модуль SimToRealMirror замыкает цикл между физическим " +
    "движком и реальным оборудованием, формируя полноценную платформу для " +
    "верификации алгоритмов управления: алгоритм разрабатывается и отлаживается " +
    "в симуляции, затем запускается на реальном роботе без изменений кода — " +
    "только сменой параметра transport или добавлением флага --mirror в точке входа."
  ));

  c.push(h.pageBreak());
  return c;
};
